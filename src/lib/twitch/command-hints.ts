/**
 * Подсказки по командам для окна «Подсказки» на оверлее. Короткие каноничные
 * имена команд для зрителя; алиасы живут в `command-parser.ts`, описание —
 * здесь. Оверлей рендерит список как есть (данные не гоняем через снапшот:
 * подсказки не зависят от состояния игры).
 */
export interface CommandHint {
	/** Короткое написание команды, как её писать в чат. */
	usage: string;
	/** Что делает команда. */
	description: string;
}

